"""Derive serving validators; all non-runtime guards remain byte-for-byte source.

Original validators and certified manifests are never edited. Checked-in outputs
are deterministic, and the serving certificate binds both originals and outputs.
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated():
    original = (ROOT / "research_platform/inference_release.py").read_text()
    start = original.index('    if m["runtime"] !=')
    end = original.index('    if set(m["source_sha256"])', start)
    inference = (
        original[:start]
        + '    verify_training_runtime(m["runtime"], repo)\n'
        + original[end:]
    )
    for name in ["resolve_release", "runtime_versions", "validate_manifest"]:
        inference = inference.replace(f"    {name},\n", "", 1)
    inference = inference.replace(
        "from scripts.build_slate import",
        "from .cloud_runtime import (\n    resolve_training_release as resolve_release,\n    validate_training_manifest as validate_manifest,\n    verify_training_runtime,\n)\nfrom scripts.build_slate import",
        1,
    )
    original = (ROOT / "season_intelligence/validate.py").read_text()
    start = original.index("    current = runtime_versions(ROOT)")
    end = original.index("    if replay:", start)
    intelligence = (
        original[:start]
        + '    verify_training_runtime(m["runtime"], ROOT)\n'
        + original[end:]
    )
    intelligence = intelligence.replace(
        "from release_utils import resolve_release, runtime_versions",
        "from research_platform.cloud_runtime import (\n    resolve_training_release as resolve_release,\n    verify_training_runtime,\n)",
    )
    intelligence = intelligence.replace(
        "from .data import", "from season_intelligence.data import"
    ).replace("from .experiment import", "from season_intelligence.experiment import")
    original = (ROOT / "research_platform/enhanced_engine.py").read_text()
    start, end = original.index("def load("), original.index("\ndef price(")
    load = original[start:end].replace(
        "sha(Path(__file__))", "sha(Path(original_engine.__file__))"
    )
    selection = (
        """import json
from pathlib import Path
import pandas as pd
from . import enhanced_engine as original_engine
from .enhanced_engine import CERTIFIED, DIRECTORY, EXPERIMENT, ROOT, eligible_rows, policy, select, sha
from .cloud_intelligence import validate as validate_experiment

"""
        + load
    )
    # Keep the existing experimental UI; only its validator import is redirected.
    ui = (ROOT / "season_intelligence/ui.py").read_text()
    ui = (
        ui.replace(
            "from .experiment import", "from season_intelligence.experiment import"
        )
        .replace(
            "from .probability import", "from season_intelligence.probability import"
        )
        .replace("from .validate import", "from .cloud_intelligence import")
    )
    return {
        "cloud_inference.py": inference,
        "cloud_intelligence.py": intelligence,
        "cloud_selection.py": selection,
        "cloud_intelligence_ui.py": ui,
    }


def write():
    for name, text in generated().items():
        (ROOT / "research_platform" / name).write_text(
            "# Generated by scripts/generate_cloud_validators.py; do not edit.\n"
            + text.rstrip()
            + "\n"
        )


if __name__ == "__main__":
    write()
