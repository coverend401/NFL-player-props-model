"""Re-certify immutable research inference under a declared serving runtime.

No training, data retrieval, production selection or bookmaker calls. Baseline
and target stages run in their genuine environments; never mock package versions.
"""

import argparse
import hashlib
import json
from datetime import UTC, datetime

from release_utils import read_json, runtime_versions, sha256
from research_platform.cloud_runtime import (
    DIRECTORY,
    POINTER,
    PROFILE_ID,
    ROOT,
    binding_paths,
    pins,
    runtime,
)
from research_platform.enhanced_engine import CERTIFIED, EXPERIMENT


def numerical_checks(cloud=False):
    if cloud:
        from research_platform.cloud_inference import validate_inference
        from research_platform.cloud_intelligence import validate
        from research_platform.cloud_selection import load
    else:
        from research_platform.enhanced_engine import load
        from research_platform.inference_release import validate_inference
        from season_intelligence.validate import validate
    inference = validate_inference(CERTIFIED, ROOT, replay=True)
    intelligence = validate(EXPERIMENT, replay=True)
    frame, top, two, _, _ = load()
    assert (len(frame), len(top), len(two), two.game_id.nunique()) == (522, 12, 20, 10)
    from research_platform.enhanced_engine import price

    samples = []
    for market, group in frame.groupby("market", sort=True):
        row = group.iloc[0].to_dict()
        line = max(0.5, int(row["baseline"]) + 0.5)
        samples.append({"market": market, "line": line, "result": price(row, line)})
    content = {
        "forecast_rows": frame[
            [
                "game_id",
                "player_id",
                "market",
                "baseline",
                "enhanced_projection",
                "q05",
                "q95",
            ]
        ].to_json(orient="records", double_precision=15),
        "top": top[["game_id", "player_id", "market"]].to_dict("records"),
        "top2": two[["game_id", "player_id", "market"]].to_dict("records"),
        "manual_probability_checks": samples,
    }
    signature = hashlib.sha256(
        json.dumps(content, sort_keys=True, allow_nan=False).encode()
    ).hexdigest()
    return {
        "inference": inference,
        "intelligence": intelligence,
        "forecasts": len(frame),
        "top_picks": len(top),
        "top2": len(two),
        "numerical_signature": signature,
    }


def check_generated():
    from scripts.generate_cloud_validators import generated

    for name, text in generated().items():
        expected = (
            "# Generated by scripts/generate_cloud_validators.py; do not edit.\n"
            + text.rstrip()
            + "\n"
        )
        if (ROOT / "research_platform" / name).read_text() != expected:
            raise ValueError(
                "Derived validator differs from declared runtime-only transform"
            )


def baseline(verify=False):
    check_generated()
    actual = runtime_versions(ROOT)
    checks = numerical_checks()
    if verify:
        recorded = read_json(DIRECTORY / "baseline_validation.json")
        if recorded["checks"] != checks or recorded[
            "original_inference_manifest"
        ] != sha256(CERTIFIED / "manifest.json"):
            raise ValueError("Original-runtime baseline replay changed")
        print(json.dumps({"status": "passed", **checks}))
        return
    report = {
        "schema": 1,
        "validated_at": datetime.now(UTC).isoformat(),
        "runtime": actual,
        "checks": checks,
        "original_inference_manifest": sha256(CERTIFIED / "manifest.json"),
    }
    (DIRECTORY / "baseline_validation.json").write_text(
        json.dumps(report, indent=2) + "\n"
    )
    print(json.dumps(checks))


def certify(verify=False):
    check_generated()
    original = read_json(DIRECTORY / "baseline_validation.json")
    if (
        original["runtime"]["packages"] != pins(ROOT / "requirements-production.lock")
        or original["runtime"]["python_minor"] != "3.14"
    ):
        raise ValueError("Baseline runtime proof changed")
    actual = runtime()
    checks = numerical_checks(cloud=True)
    if original["checks"] != checks or original[
        "original_inference_manifest"
    ] != sha256(CERTIFIED / "manifest.json"):
        raise ValueError("Cross-runtime forecast or probability replay changed")
    if verify:
        from research_platform.cloud_runtime import admit

        admit()
        print(json.dumps({"status": "passed", **checks}))
        return
    certificate = {
        "schema": 1,
        "profile_id": PROFILE_ID,
        "status": "passed",
        "validated_at": datetime.now(UTC).isoformat(),
        "forecast_release": "research-week11-frozen-20261120-r2",
        "training_runtime": read_json(CERTIFIED / "manifest.json")["runtime"],
        "baseline_validation_runtime": original["runtime"],
        "serving_runtime": actual,
        "permitted_package_change": {
            "certifi": {"from": "2026.10.23", "to": "2026.11.20"}
        },
        "checks": checks,
        "files": {name: sha256(path) for name, path in sorted(binding_paths().items())},
    }
    original_manifest = read_json(CERTIFIED / "manifest.json")
    certificate["model_parent"] = original_manifest["model_parent"]
    certificate["model_lineage"] = original_manifest["models"]
    path = DIRECTORY / "certificate.json"
    path.write_text(json.dumps(certificate, indent=2) + "\n")
    POINTER.write_text(
        json.dumps(
            {
                "profile_id": PROFILE_ID,
                "path": str(path.relative_to(ROOT)),
                "sha256": sha256(path),
            },
            indent=2,
        )
        + "\n"
    )
    from research_platform.cloud_runtime import admit

    admit()
    print(json.dumps({"status": "passed", **checks}))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--baseline", action="store_true")
    parser.add_argument("--verify", action="store_true")
    parser.add_argument("--verify-baseline", action="store_true")
    args = parser.parse_args()
    if args.verify_baseline:
        baseline(verify=True)
    elif args.baseline:
        baseline()
    else:
        certify(args.verify)
