"""Deterministic runtime-only derivation; original operational contract is immutable."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generated():
    text = (ROOT / "weekly_learning/contract.py").read_text()
    start = text.index('    if m["runtime"] !=')
    end = text.index('    if set(m["source_sha256"])', start)
    text = (
        text[:start] + '    verify_training_runtime(m["runtime"], repo)\n' + text[end:]
    )
    for name in ["runtime_versions", "validate_manifest"]:
        text = text.replace(f"    {name},\n", "", 1)
    text = text.replace(
        "from research_platform.inference_builder import (",
        "from research_platform.cloud_runtime import verify_training_runtime, validate_training_manifest as validate_manifest\nfrom research_platform.inference_builder import (",
        1,
    )
    text = text.replace(
        "from .store import ROOT, encoded, sha",
        "from weekly_learning.store import ROOT, encoded, sha",
    )
    return (
        "# Generated by scripts/generate_weekly_serving.py; runtime substitution only.\n"
        + text
    )


if __name__ == "__main__":
    (ROOT / "research_platform/cloud_weekly_contract.py").write_text(generated())
